export function getSeoTool(slug: string): SeoTool | undefined {
  return seoTools.find((tool) => tool.slug === slug);
}

export function getRelatedTools(slug: string): SeoTool[] {
  const tool = getSeoTool(slug);
  if (!tool) return [];
  return tool.relatedSlugs
    .map((relatedSlug) => getSeoTool(relatedSlug))
    .filter((t): t is SeoTool => t !== undefined);
}
